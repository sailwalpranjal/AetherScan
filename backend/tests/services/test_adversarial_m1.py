# 3. FCS Dispersion Penalty Stress Tests
# =============================================================================

def test_fcs_dispersion_penalty_spectrum():
    """
    ADVERSARIAL CHALLENGE 4: FCS Mathematical Properties.
    Formula: FCS = (sum(DQS_i * w_i) / sum(w_i)) * max(0.0, 1.0 - sigma / mu)
    """
    # 1. Single sensor: dispersion is 0, penalty is 1.0
    assert calculate_fcs([0.85], [45.0]) == pytest.approx(0.85, abs=1e-4)
    assert calculate_fcs([0.50], [100.0]) == pytest.approx(0.50, abs=1e-4)
    assert calculate_fcs([0.0], [50.0]) == 0.0

    # 2. Identical observations: sigma = 0, penalty = 1.0
    fcs_identical = calculate_fcs([0.8, 0.9, 0.7], [60.0, 60.0, 60.0])
    assert fcs_identical == pytest.approx(0.800000, abs=1e-4)

    # 3. Mild dispersion: mu = 50, values = [45, 55], sigma = 5, ratio = 0.10 -> penalty 0.90
    fcs_mild = calculate_fcs([0.9, 0.9], [45.0, 55.0])
    assert fcs_mild == pytest.approx(0.9 * 0.90, abs=1e-4)

    # 4. Severe dispersion (sigma / mu == 1.0): values [0, 100], mu = 50, sigma = 50 -> ratio = 1.0 -> FCS = 0.0
    fcs_severe_1 = calculate_fcs([0.95, 0.95], [0.0, 100.0])
    assert fcs_severe_1 == 0.0

    # 5. Extreme dispersion (sigma / mu > 1.0): values [1, 1, 500] -> FCS = 0.0
    fcs_severe_2 = calculate_fcs([0.9, 0.9, 0.9], [1.0, 1.0, 500.0])
    assert fcs_severe_2 == 0.0

    # 6. Zero mean edge cases:
    # All zero: penalty = 1.0
    assert calculate_fcs([0.8, 0.8], [0.0, 0.0]) == pytest.approx(0.8, abs=1e-4)
    # Cancelling non-zero: mu = 0 but values != 0 -> penalty = 0.0
    assert calculate_fcs([0.8, 0.8], [-10.0, 10.0]) == 0.0

    # 7. Confidence tiers mapping
    assert get_fcs_confidence_level(0.85) == "HIGH"
    assert get_fcs_confidence_level(0.80) == "MEDIUM"
    assert get_fcs_confidence_level(0.55) == "MEDIUM"
    assert get_fcs_confidence_level(0.50) == "LOW"
    assert get_fcs_confidence_level(0.10) == "LOW"
    assert get_fcs_confidence_level(0.0) == "LOW"

    # 8. Corrupt and adversarial inputs:
    # NaN and inf in values
    assert calculate_fcs([0.8, 0.8], [float("nan"), 50.0]) == 0.0
    assert calculate_fcs([0.8, 0.8], [float("inf"), 50.0]) == 0.0
    # Empty inputs
    assert calculate_fcs([], []) == 0.0
    # Mismatched lengths raise ValueError
    with pytest.raises(ValueError):
        calculate_fcs([0.8], [50.0, 60.0])


