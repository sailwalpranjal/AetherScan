# Helper: Geodesic destination point given start, bearing (deg), and distance (km)
# =============================================================================
def destination_point(lat: float, lon: float, distance_km: float, bearing_deg: float):
    """Calculate destination coordinate using great-circle direct problem."""
    d_div_r = distance_km / EARTH_RADIUS_KM
    theta = math.radians(bearing_deg)
    phi1 = math.radians(lat)
    lambda1 = math.radians(lon)

    sin_phi2 = math.sin(phi1) * math.cos(d_div_r) + math.cos(phi1) * math.sin(d_div_r) * math.cos(theta)
    phi2 = math.asin(max(-1.0, min(1.0, sin_phi2)))
    y = math.sin(theta) * math.sin(d_div_r) * math.cos(phi1)
    x = math.cos(d_div_r) - math.sin(phi1) * math.sin(phi2)
    lambda2 = lambda1 + math.atan2(y, x)

    return math.degrees(phi2), (math.degrees(lambda2) + 540.0) % 360.0 - 180.0


