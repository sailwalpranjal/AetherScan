def test_dqs_spatial_distance_decay_benchmarks():
    """
    ADVERSARIAL CHALLENGE 3: Verify exact DQS distance decay formula:
    Q_spatial = max(0.1, 1.0 - 0.9 * (d / 50.0))
    Benchmarks:
    - 0 km -> 1.000000
    - 10 km -> 0.820000
    - 25 km -> 0.550000
    - 50 km -> 0.100000
    - 75 km -> 0.100000 (floor clamped)
    """
    assert calculate_spatial_representativeness(0.0) == pytest.approx(1.000000, abs=1e-5)
    assert calculate_spatial_representativeness(10.0) == pytest.approx(0.820000, abs=1e-5)
    assert calculate_spatial_representativeness(25.0) == pytest.approx(0.550000, abs=1e-5)
    assert calculate_spatial_representativeness(50.0) == pytest.approx(0.100000, abs=1e-5)
    assert calculate_spatial_representativeness(75.0) == pytest.approx(0.100000, abs=1e-5)
    assert calculate_spatial_representativeness(100.0) == pytest.approx(0.100000, abs=1e-5)

    # Non-finite and negative inputs
    assert calculate_spatial_representativeness(-5.0) == pytest.approx(1.000000, abs=1e-5)
    assert calculate_spatial_representativeness(float("nan")) == 0.1
    assert calculate_spatial_representativeness(float("inf")) == 0.1

    # End-to-end calculate_dqs at benchmark distances for fresh, reference, valid data
    now_ts = datetime.now(timezone.utc).isoformat()
    dqs_0 = calculate_dqs(50.0, "pm25", now_ts, distance_km=0.0, sensor_type="reference")
    assert dqs_0 == pytest.approx(1.000000, abs=1e-4)

    dqs_25 = calculate_dqs(50.0, "pm25", now_ts, distance_km=25.0, sensor_type="reference")
    assert dqs_25 == pytest.approx(0.550000, abs=1e-4)

    dqs_50 = calculate_dqs(50.0, "pm25", now_ts, distance_km=50.0, sensor_type="reference")
    assert dqs_50 == pytest.approx(0.100000, abs=1e-4)


