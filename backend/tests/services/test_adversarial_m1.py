# 7. FCS Weighted Dispersion & Edge Cases
# =============================================================================

def test_fcs_weighted_dispersion_and_edge_cases():
    """
    ADVERSARIAL CHALLENGE 8: FCS source weights, unequal weighting, and extreme cases.
    """
    # Unequal weights: high weight on DQS=0.9, low weight on DQS=0.3
    # Values: [50.0, 50.0] (no dispersion, sigma = 0)
    # weighted DQS = (0.9 * 3.0 + 0.3 * 1.0) / 4.0 = 3.0 / 4.0 = 0.75
    fcs_weighted = calculate_fcs([0.9, 0.3], [50.0, 50.0], weights=[3.0, 1.0])
    assert fcs_weighted == pytest.approx(0.750000, abs=1e-4)

    # Negative and zero weights handled cleanly
    # Weight of 0 should be ignored in weighted DQS
    fcs_zero_weight = calculate_fcs([0.9, 0.3], [50.0, 50.0], weights=[1.0, 0.0])
    assert fcs_zero_weight == pytest.approx(0.900000, abs=1e-4)

    # All weights zero -> returns 0.0
    assert calculate_fcs([0.9, 0.8], [50.0, 50.0], weights=[0.0, 0.0]) == 0.0

    # Negative weight clamped or treated as 0.0
    fcs_neg_weight = calculate_fcs([0.9, 0.3], [50.0, 50.0], weights=[1.0, -1.0])
    assert fcs_neg_weight == pytest.approx(0.900000, abs=1e-4)

